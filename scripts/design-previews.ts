import { readFileSync, writeFileSync } from 'node:fs';
import { GARMENTS, buildGarment, garmentDisplayAngle } from '../src/fold/garments';
import { buildTimeline, evaluateFrame, posePoint } from '../src/fold/timeline';

// Finished material facets, not illustrative substitutes. Generate at authoring
// time so opening the chooser doesn't build 22 fold timelines on a phone.
const previews: Record<string, { svg: string; steps: number }> = {};
const n = (x: number) => Number(x.toFixed(4));
for (const g of GARMENTS) {
  const timeline = buildTimeline(buildGarment(g.id).ops);
  const last = timeline.ops.at(-1)!, frame = evaluateFrame(last, 1);
  const angle = garmentDisplayAngle(g.id), c = Math.cos(angle), s = Math.sin(angle);
  const polygons = last.pieces.map(piece => {
    const points = piece.poly.map(p => {
      const [x, y, z] = posePoint(frame, piece.index * 12, p.x, p.y);
      return [x * c - y * s, -(x * s + y * c), z];
    });
    return { points, front: frame[piece.index * 12 + 10] > 0,
      depth: points.reduce((sum, p) => sum + p[2], 0) / points.length };
  }).sort((a, b) => a.depth - b.depth);
  const points = polygons.flatMap(p => p.points);
  const minX = Math.min(...points.map(p => p[0])), maxX = Math.max(...points.map(p => p[0]));
  const minY = Math.min(...points.map(p => p[1])), maxY = Math.max(...points.map(p => p[1]));
  const pad = Math.max(maxX - minX, maxY - minY) * .1;
  const box = [minX - pad, minY - pad, maxX - minX + 2 * pad, maxY - minY + 2 * pad].map(n).join(' ');
  const shapes = polygons.map(p => `<polygon points="${p.points.map(v => `${n(v[0])},${n(v[1])}`).join(' ')}" fill="${p.front ? '#637c75' : '#dacbb5'}" stroke="#465d57" stroke-width=".005" stroke-linejoin="round"/>`).join('');
  previews[g.id] = { svg: `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${box}" aria-hidden="true">${shapes}</svg>`, steps: timeline.ops.length };
}
const output = '// Generated by scripts/design-previews.ts from the finished default constructions.\nexport const DESIGN_PREVIEWS: Record<string, { svg: string; steps: number }> = ' + JSON.stringify(previews) + ';\n';
const path = new URL('../src/ui/designPreviews.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output) throw new Error('Design previews are stale: run npm run previews');
  console.log(`Verified ${GARMENTS.length} finished design previews`);
} else writeFileSync(path, output);
